"""Generate runtime sockets from the audited model contract; no Blender edits."""
import argparse
import json
import math
import runpy
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / 'src/Data/Scripts/ArcanePower/ThermalModels.cs'


def vector(values, integer=False):
    converted = [-values[0], values[2], values[1]]
    if integer:
        converted = [values[0], values[2], values[1]]
    return ('new Vector3I(' if integer else 'new Vector3(') + ', '.join(
        str(int(v)) if integer else format(round(v, 6), '.6g') + 'f' for v in converted) + ')'


def generate():
    models = json.loads((ROOT / 'validation/thermal-models/models.json').read_text())
    contract = runpy.run_path(str(ROOT / 'assets/thermal_model_contract.py'))
    assert set(models) == set(contract['SPECS'])
    models = contract['runtime_models'](models)
    rows = ['// Generated by tools/build_thermal_runtime_contract.py from audited model ports.',
            'using System.Collections.Generic;', 'using VRageMath;', '', 'namespace ArcanePower', '{',
            '    public static class ThermalModels', '    {',
            '        public static readonly Dictionary<string, ThermalModel> All = Create();',
            '        private static Dictionary<string, ThermalModel> Create()', '        {',
            '            var models = new Dictionary<string, ThermalModel>();']
    rig = json.loads((ROOT / 'assets/thermal-manifold-runtime.json').read_text())
    assert rig['revision'] == 4 and [r['id'] for r in rig['bays']] == ['LA', 'LB', 'RA', 'RB']
    rows[8:8] = [
        '        public static readonly string[] ManifoldBays = { "LA", "LB", "RA", "RB" };',
        '        public static readonly double[] ManifoldAngles = { ' + ', '.join(repr(r['panel_angle']) for r in rig['bays']) + ' };']
    rotors = json.loads((ROOT / 'assets/thermal-rotor-runtime.json').read_text())
    assert rotors['revision'] == 4 and [r['id'] for r in rotors['rotors']] == ['turbine', 'compressor']
    rows[8:8] = [
        '        public static readonly string[] RotorNames = { ' + ', '.join('"' + r['subpart'] + '"' for r in rotors['rotors']) + ' };',
        '        public static readonly Vector3[] RotorPivots = { ' + ', '.join(vector(r['pivot_blender']) for r in rotors['rotors']) + ' };']
    exhaust=models['Atmospheric cooler']['air_exhaust_samples']
    assert len(exhaust)==18 and all(len(p)==3 and all(math.isfinite(v) for v in p) for p in exhaust)
    rows[8:8] = ['        public static readonly Vector3[] AirCoolerExhaustSamples = { '
                 + ', '.join(vector(p) for p in exhaust) + ' };']
    for name, model in models.items():
        kind = ('Reactor' if name == 'Reactor housing' else 'Train' if name.startswith('Brayton train')
                else 'AirCooler' if name.startswith('Atmospheric cooler') else 'Radiator' if name.startswith('Space radiator')
                else 'RadiatorPanel' if name.startswith('Radiator panel') else 'Pipe')
        grade = 3 if 'upgraded' in name or kind == 'Pipe' else 0
        cooler = kind in ('AirCooler', 'Radiator', 'RadiatorPanel')
        if kind == 'Train':
            rating = 62500 if grade == 3 else 4375
        elif kind == 'Reactor':
            rating = 250000
        elif cooler:
            # Retain historical heat-storage capacity for existing saves.
            rating = 250000 if grade == 3 else 25000
        else:
            rating = 2500000
        cooling = (20000 if grade == 3 else 2000) if cooler else 0
        if kind == 'AirCooler':
            cooling = 50000 if grade == 3 else 5000
        subtype = model['subtype']
        assert model['cells_se'] == [model['cells_blender'][i] for i in (0, 2, 1)]
        rows += [f'            models.Add("{subtype}", new ThermalModel {{',
                 f'                Subtype = "{subtype}", Cells = {vector(model["cells_blender"], True)},',
                 f'                Kind = ThermalKind.{kind}, Grade = {grade}, RatingMW = {rating}, CoolingMW = {cooling}, Ports = new ThermalPort[] {{']
        source = models[contract['PIPE_ALIASES'].get(name, contract['COOLER_UPGRADES'].get(name, name))]
        # Compatibility IDs render the canonical model, so their socket geometry
        # must agree with it before an old saved block can share that asset.
        assert [{k:v for k,v in p.items() if k != 'type'} for p in model['ports']] == [
            {k:v for k,v in p.items() if k != 'type'} for p in source['ports']]
        for p in source['ports']:
            circuit = contract['runtime_circuit'](name, p['type'])
            role = ', true' if p.get('reactor_transition') else ''
            rows.append(f'                    new ThermalPort("{circuit}", {vector(p["position"])}, {vector(p["normal"])}, {vector(p["hot_axis"])}{role}),')
        rows.append('                } });')
    rows += ['            return models;', '        }', '    }']
    for kind, base_type, class_name in [('Train', 'Reactor', 'ThermalTrain'), ('Other', 'UpgradeModule', 'ThermalMachine')]:
        names = [m['subtype'] for n, m in models.items() if
                 (n.startswith('Brayton train') if kind == 'Train' else not n.startswith('Brayton train') and n != 'Reactor housing')]
        rows += ['    [VRage.Game.Components.MyEntityComponentDescriptor(',
                 f'        typeof(Sandbox.Common.ObjectBuilders.MyObjectBuilder_{base_type}), false,',
                 '        ' + ', '.join('"' + n + '"' for n in names) + ')]',
                 f'    public sealed class {class_name} : ThermalBlock {{ }}']
    rows.append('}')
    return '\n'.join(rows) + '\n'


def generate_flow():
    models = json.loads((ROOT / 'validation/thermal-models/models.json').read_text())
    data = json.loads((ROOT / 'assets/thermal-flow-paths.json').read_text())
    assert data['revision'] == 1 and set(data['models']) == {m['subtype'] for m in models.values()}
    contract = runpy.run_path(str(ROOT / 'assets/thermal_model_contract.py'))
    models = contract['runtime_models'](models)
    rows = ['// Generated from the authored pressure-pipe centrelines.',
            'using System.Collections.Generic;', 'using VRageMath;', 'namespace ArcanePower {',
            'public static class ThermalFlowModels {',
            'public static readonly Dictionary<string, ThermalFlowPath[]> All = new Dictionary<string, ThermalFlowPath[]> {']
    for name, model in models.items():
        subtype = model['subtype']
        source = models[contract['PIPE_ALIASES'].get(name, contract['COOLER_UPGRADES'].get(name, name))]
        paths = data['models'][source['subtype']]
        if not model['ports']: continue
        assert paths, subtype
        rows.append('{"' + subtype + '", new ThermalFlowPath[] {')
        for path in paths:
            assert len(path['points']) >= 2 and 0 < path['radius'] <= .25
            assert all(math.isfinite(v) for p in path['points'] for v in p)
            assert path['internal'] or 0 <= path['port'] < len(model['ports'])
            coords = ', '.join(vector(point) for point in path['points'])
            rows.append('new ThermalFlowPath("%s", %s, %d, %sf, %s, new Vector3[] { %s }),' % (
                path['circuit'] if path['internal'] else contract['runtime_circuit'](name, path['circuit']), str(path['hot']).lower(), path['port'], str(path['radius']),
                str(path['internal']).lower(), coords))
        rows.append('}},')
    rows += ['};', '}', '}']
    return '\n'.join(rows) + '\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    content = generate()
    flow_target = TARGET.with_name('ThermalFlowModels.cs')
    flow_content = generate_flow()
    if args.check:
        if not TARGET.exists() or TARGET.read_text() != content:
            raise SystemExit('Runtime socket contract is stale; run this tool without --check')
        if not flow_target.exists() or flow_target.read_text() != flow_content:
            raise SystemExit('Runtime flow paths are stale; run this tool without --check')
        print('All runtime socket and flow contracts match the authored models')
    else:
        TARGET.write_text(content)
        flow_target.write_text(flow_content)
        print(TARGET)
